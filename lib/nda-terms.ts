/**
 * NDA 전문 (SSoT · 2026-08-19)
 *
 * 체결 시점의 전문을 그대로 스냅샷으로 남긴다(nda_documents.content_text).
 * 약관을 고치면 TERMS_VERSION 을 올린다 — 과거 체결본은 그때의 전문 그대로 보관된다.
 *
 * 공개 범위 정책은 운영설계서와 일치해야 한다:
 *   NDA 승인 = 매물 세부내역 열람. 채권기관·담당자명·직책·연락처는 **NDA 후에도 비공개**이며
 *   협의 단계에서 운영사를 통해서만 공유된다.
 */

export const TERMS_VERSION = 'v1'

export type NdaTermsContext = {
  /** 관리번호 (N26-1) */
  listingNo: string
  /** 서명자명 */
  signer: string
  /** 서명자 이메일 */
  email: string
  /** 체결 일시 (ISO) */
  agreedAt: string
  /** 소속 (선택) */
  company?: string
}

const d = (iso: string) => {
  const t = new Date(iso)
  if (isNaN(t.getTime())) return iso
  return `${t.getFullYear()}년 ${t.getMonth() + 1}월 ${t.getDate()}일`
}

/** 체결 전문 생성 — 화면 표시와 PDF 보관본이 같은 문장을 쓴다 */
