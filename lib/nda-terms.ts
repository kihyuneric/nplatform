    '',
    '제3조 (비밀유지 의무)',
    '① 수령인은 비밀정보를 본건 매입 검토 목적으로만 사용하며, 운영사의 사전 서면 동의 없이 제3자에게 누설·공개·배포하지 아니한다.',
    '② 수령인은 비밀정보를 임직원 중 본건 검토에 직접 필요한 자에게만 공유하며, 그 자의 의무 위반에 대하여 수령인이 책임을 진다.',
